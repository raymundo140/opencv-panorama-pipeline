# ============================================================
# DEBUG VISUALIZATION
# ============================================================

def create_ransac_visualization(
    image_a,
    image_b,
    points_a,
    points_b,
    inlier_mask,
    max_drawn=200,
):
    """
    Creates a side-by-side visualization.

    Green:
        RANSAC inlier

    Red:
        rejected match / outlier
    """

    if (
        image_a is None
        or image_b is None
    ):

        raise ValueError(
            "Images cannot be None."
        )

    # --------------------------------------------------------
    # Convert grayscale if necessary
    # --------------------------------------------------------

    if len(
        image_a.shape
    ) == 2:

        image_a = cv2.cvtColor(
            image_a,
            cv2.COLOR_GRAY2BGR,
        )

    if len(
        image_b.shape
    ) == 2:

        image_b = cv2.cvtColor(
            image_b,
            cv2.COLOR_GRAY2BGR,
        )

    height_a, width_a = (
        image_a.shape[:2]
    )

    height_b, width_b = (
        image_b.shape[:2]
    )

    canvas_height = max(
        height_a,
        height_b,
    )

    canvas_width = (
        width_a
        + width_b
    )

    canvas = np.zeros(
        (
            canvas_height,
            canvas_width,
            3,
        ),
        dtype=np.uint8,
    )

    canvas[
        0:height_a,
        0:width_a,
    ] = image_a

    canvas[
        0:height_b,
        width_a:width_a + width_b,
    ] = image_b

    # --------------------------------------------------------
    # Limit number drawn so debug image remains readable
    # --------------------------------------------------------

    number_points = len(
        points_a
    )

    number_drawn = min(
        number_points,
        max_drawn,
    )

    for index in range(
        number_drawn
    ):

        point_a = points_a[
            index
        ]

        point_b = points_b[
            index
        ]

        x_a = int(
            round(
                point_a[0]
            )
        )

        y_a = int(
            round(
                point_a[1]
            )
        )

        x_b = int(
            round(
                point_b[0]
            )
        ) + width_a

        y_b = int(
            round(
                point_b[1]
            )
        )

        if inlier_mask[index]:

            # Green = RANSAC inlier
            color = (
                0,
                255,
                0,
            )

        else:

            # Red = rejected match
            color = (
                0,
                0,
                255,
            )

        cv2.circle(
            canvas,
            (
                x_a,
                y_a,
            ),
            4,
            color,
            -1,
        )

        cv2.circle(
            canvas,
            (
                x_b,
                y_b,
            ),
            4,
            color,
            -1,
        )

        cv2.line(
            canvas,
            (
                x_a,
                y_a,
            ),
            (
                x_b,
                y_b,
            ),
            color,
            1,
            cv2.LINE_AA,
        )

    return canvas


# ============================================================
# FIND IMAGE
# ============================================================

def find_image(
    image_dir,
    image_name,
):
    """
    Finds the corresponding undistorted panorama image.
    """

    image_path = (
        Path(image_dir)
        / image_name
    )

    if not image_path.exists():

        raise RuntimeError(
            "\nImage not found:\n"
            f"{image_path}\n"
        )

    return image_path


# ============================================================
# PROCESS ALL PAIRS
# ============================================================

def estimate_all_homographies(
    matches_dir,
    image_dir,
    output_dir,
    reprojection_threshold=3.0,
    confidence=0.995,
    max_iterations=5000,
):
    """
    Estimates a RANSAC homography for every adjacent
    panorama pair.
    """

    matches_dir = Path(
        matches_dir
    )

    image_dir = Path(
        image_dir
    )

    output_dir = Path(
        output_dir
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    debug_dir = (
        output_dir.parent
        / "debug"
        / "homographies"
    )

    debug_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    match_files = (
        find_match_files(
            matches_dir
        )
    )

    if not match_files:

        raise RuntimeError(
            "\nNo feature match files found in:\n"
            f"{matches_dir}\n"
        )

    print()
    print("========================================")
    print(" HOMOGRAPHY ESTIMATION WITH RANSAC")
    print("========================================")
    print()

    print(
        f"Match files: "
        f"{len(match_files)}"
    )

    print(
        f"RANSAC reprojection threshold: "
        f"{reprojection_threshold:.2f} px"
    )

    print(
        f"RANSAC confidence: "
        f"{confidence}"
    )

    print(
        f"Maximum RANSAC iterations: "
        f"{max_iterations}"
    )

    print()

    results = []

    # ========================================================
    # PROCESS EACH IMAGE PAIR
    # ========================================================

    for index, match_file in enumerate(
        match_files,
        start=1,
    ):

        pair = load_match_file(
            match_file
        )

        print(
            f"[{index}/{len(match_files)}] "
            f"{pair['image_a']} "
            f"-> "
            f"{pair['image_b']}"
        )

        points_a = (
            pair[
                "points_a"
            ]
        )

        points_b = (
            pair[
                "points_b"
            ]
        )

        number_matches = len(
            points_a
        )

        print(
            f"  Feature matches: "
            f"{number_matches}"
        )

        # ----------------------------------------------------
        # Need minimum four matches
        # ----------------------------------------------------

        if number_matches < 4:

            print(
                "  ERROR: fewer than 4 matches."
            )

            print(
                "  Homography skipped."
            )

            print()

            results.append(
                {
                    "pair_id": (
                        pair[
                            "pair_id"
                        ]
                    ),

                    "success": False,

                    "reason": (
                        "fewer than 4 matches"
                    ),
                }
            )

            continue

        try:

            result = (
                estimate_homography_ransac(
                    points_a,
                    points_b,
                    reprojection_threshold=(
                        reprojection_threshold
                    ),
                    confidence=(
                        confidence
                    ),
                    max_iterations=(
                        max_iterations
                    ),
                )
            )

        except RuntimeError as error:

            print(
                f"  ERROR: {error}"
            )

            print()

            results.append(
                {
                    "pair_id": (
                        pair[
                            "pair_id"
                        ]
                    ),

                    "success": False,

                    "reason": str(
                        error
                    ),
                }
            )

            continue

        # ----------------------------------------------------
        # Statistics
        # ----------------------------------------------------

        print(
            f"  RANSAC inliers: "
            f"{result['number_inliers']}/"
            f"{result['number_matches']}"
        )

        print(
            f"  Inlier ratio: "
            f"{result['inlier_ratio'] * 100:.1f}%"
        )

        print(
            f"  Mean reprojection error: "
            f"{result['mean_error']:.3f} px"
        )

        print(
            f"  RMS reprojection error: "
            f"{result['rms_error']:.3f} px"
        )

        print(
            f"  Median reprojection error: "
            f"{result['median_error']:.3f} px"
        )

        # ----------------------------------------------------
        # Basic warnings
        # ----------------------------------------------------

        if (
            result[
                "number_inliers"
            ]
            < 10
        ):

            print(
                "  WARNING: very few RANSAC inliers."
            )

        if (
            result[
                "inlier_ratio"
            ]
            < 0.30
        ):

            print(
                "  WARNING: low inlier ratio."
            )

        # ----------------------------------------------------
        # Print H
        # ----------------------------------------------------

        print()

        print(
            "  H (image A -> image B):"
        )

        for row in (
            result[
                "homography_a_to_b"
            ]
        ):

            print(
                "   ",
                row,
            )

        # ----------------------------------------------------
        # Save homography
        # ----------------------------------------------------

        output_file = (
            output_dir
            / (
                f"pair_"
                f"{pair['pair_id']:02d}"
                f"_homography.npz"
            )
        )

        save_homography(
            output_file=(
                output_file
            ),
            pair_data=(
                pair
            ),
            result=(
                result
            ),
            reprojection_threshold=(
                reprojection_threshold
            ),
            confidence=(
                confidence
            ),
            max_iterations=(
                max_iterations
            ),
        )

        print()

        print(
            f"  Saved: "
            f"{output_file}"
        )

        # ----------------------------------------------------
        # Debug visualization
        # ----------------------------------------------------

        image_path_a = find_image(
            image_dir,
            pair[
                "image_a"
            ],
        )

        image_path_b = find_image(
            image_dir,
            pair[
                "image_b"
            ],
        )

        image_a = cv2.imread(
            str(
                image_path_a
            )
        )

        image_b = cv2.imread(
            str(
                image_path_b
            )
        )

        visualization = (
            create_ransac_visualization(
                image_a,
                image_b,
                points_a,
                points_b,
                result[
                    "inlier_mask"
                ],
            )
        )

        debug_file = (
            debug_dir
            / (
                f"pair_"
                f"{pair['pair_id']:02d}"
                f"_ransac.jpg"
            )
        )

        cv2.imwrite(
            str(
                debug_file
            ),
            visualization,
        )

        print(
            f"  Debug: "
            f"{debug_file}"
        )

        print()

        results.append(
            {
                "pair_id": (
                    pair[
                        "pair_id"
                    ]
                ),

                "image_a": (
                    pair[
                        "image_a"
                    ]
                ),

                "image_b": (
                    pair[
                        "image_b"
                    ]
                ),

                "success": True,

                "matches": (
                    result[
                        "number_matches"
                    ]
                ),

                "inliers": (
                    result[
                        "number_inliers"
                    ]
                ),

                "inlier_ratio": (
                    result[
                        "inlier_ratio"
                    ]
                ),

                "rms_error": (
                    result[
                        "rms_error"
                    ]
                ),

                "output_file": str(
                    output_file
                ),
            }
        )

    # ========================================================
    # SAVE SUMMARY
    # ========================================================

    summary_file = (
        output_dir
        / "homography_summary.json"
    )

    with open(
        summary_file,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            {
                "ransac_threshold": (
                    reprojection_threshold
                ),

                "confidence": (
                    confidence
                ),

                "max_iterations": (
                    max_iterations
                ),

                "pairs": (
                    results
                ),
            },
            file,
            indent=4,
        )

    # ========================================================
    # SUMMARY
    # ========================================================

    successful = [
        result

        for result in results

        if result.get(
            "success",
            False,
        )
    ]

    print("========================================")
    print(" HOMOGRAPHY ESTIMATION COMPLETE")
    print("========================================")
    print()

    print(
        f"Pairs processed: "
        f"{len(results)}"
    )

    print(
        f"Successful homographies: "
        f"{len(successful)}/"
        f"{len(results)}"
    )

    if successful:

        average_ratio = np.mean(
            [
                result[
                    "inlier_ratio"
                ]

                for result in successful
            ]
        )

        average_rms = np.mean(
            [
                result[
                    "rms_error"
                ]

                for result in successful
            ]
        )

        print(
            f"Average inlier ratio: "
            f"{average_ratio * 100:.1f}%"
        )

        print(
            f"Average RANSAC RMS error: "
            f"{average_rms:.3f} px"
        )

    print()

    print(
        "Homographies:"
    )

    print(
        output_dir
    )

    print()

    print(
        "RANSAC debug images:"
    )

    print(
        debug_dir
    )

    print()

    print(
        "Summary:"
    )

    print(
        summary_file
    )

    print()

    return results


