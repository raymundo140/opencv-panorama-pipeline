# SAVE HOMOGRAPHY
# ============================================================

def save_homography(
    output_file,
    pair_data,
    result,
    reprojection_threshold,
    confidence,
    max_iterations,
):
    """
    Saves the transformation and RANSAC results.
    """

    output_file = Path(
        output_file
    )

    output_file.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    points_a = (
        pair_data[
            "points_a"
        ]
    )

    points_b = (
        pair_data[
            "points_b"
        ]
    )

    inlier_mask = (
        result[
            "inlier_mask"
        ]
    )

    np.savez_compressed(
        output_file,

        pair_id=np.array(
            pair_data[
                "pair_id"
            ]
        ),

        image_a=np.array(
            pair_data[
                "image_a"
            ]
        ),

        image_b=np.array(
            pair_data[
                "image_b"
            ]
        ),

        # ----------------------------------------------------
        # Transformations
        # ----------------------------------------------------

        homography_a_to_b=(
            result[
                "homography_a_to_b"
            ]
        ),

        homography_b_to_a=(
            result[
                "homography_b_to_a"
            ]
        ),

        # ----------------------------------------------------
        # All matched points
        # ----------------------------------------------------

        points_a=points_a,

        points_b=points_b,

        # ----------------------------------------------------
        # RANSAC result
        # ----------------------------------------------------

        inlier_mask=(
            inlier_mask.astype(
                np.uint8
            )
        ),

        inlier_points_a=(
            points_a[
                inlier_mask
            ]
        ),

        inlier_points_b=(
            points_b[
                inlier_mask
            ]
        ),

        number_matches=np.array(
            result[
                "number_matches"
            ]
        ),

        number_inliers=np.array(
            result[
                "number_inliers"
            ]
        ),

        inlier_ratio=np.array(
            result[
                "inlier_ratio"
            ]
        ),

        mean_reprojection_error=np.array(
            result[
                "mean_error"
            ]
        ),

        rms_reprojection_error=np.array(
            result[
                "rms_error"
            ]
        ),

        median_reprojection_error=np.array(
            result[
                "median_error"
            ]
        ),

        reprojection_errors=(
            result[
                "all_errors"
            ]
        ),

        # ----------------------------------------------------
        # RANSAC configuration
        # ----------------------------------------------------

        ransac_threshold=np.array(
            reprojection_threshold
        ),

        ransac_confidence=np.array(
            confidence
        ),

        ransac_max_iterations=np.array(
            max_iterations
        ),
    )


